#!/usr/bin/env node
// Materializes the Functions copy of the Community Prompt routing decisions
// (#1275) from the ONE implementation in `src/data/communityPrompts.ts`.
//
// `functions/tsconfig.json` sets `rootDir: "src"`, so the Functions package
// cannot import runtime code from the app package. The `approvePrompts`
// callable still has to route on the same five decisions the client uses to
// default a submission's Day and to tell a submitter "scheduled", so the
// marked block is copied byte-for-byte into
// `functions/src/communityPromptRouting.generated.ts`. Only the import of
// `normalizePool` differs, and it lives outside the block: the app resolves it
// from `src/game/pool.ts`, Functions from `functions/src/poolVocab.ts`, and the
// parity suite holds those two to the same answers.
//
// Usage:
//   node scripts/materialize-community-prompt-routing-functions.mjs          # write
//   node scripts/materialize-community-prompt-routing-functions.mjs --check  # verify
//
// `--check` is pinned by tests/functions/community-prompt-routing-parity.test.ts,
// so an edit to the source block without a re-run fails the Functions suite.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const sourcePath = path.join(repoRoot, 'src/data/communityPrompts.ts');
const outputPath = path.join(repoRoot, 'functions/src/communityPromptRouting.generated.ts');
const sourceRef = 'src/data/communityPrompts.ts#community-prompt-routing';
const checkOnly = process.argv.slice(2).includes('--check');

const unknownArgs = process.argv.slice(2).filter((arg) => arg !== '--check');
if (unknownArgs.length > 0) {
  throw new Error(`Unknown argument(s): ${unknownArgs.join(', ')}`);
}

const source = await readFile(sourcePath, 'utf8');
const blockPattern = /^\/\/ <community-prompt-routing>\r?\n([\s\S]*?)^\/\/ <\/community-prompt-routing>\r?$/gm;
const blocks = [...source.matchAll(blockPattern)].map((match) => match[1].replace(/\r\n/g, '\n').trimEnd());

if (blocks.length !== 1) {
  throw new Error(`Expected exactly 1 community-prompt-routing block in ${sourceRef}; found ${blocks.length}.`);
}

const expected = `/**
 * @generated by scripts/materialize-community-prompt-routing-functions.mjs
 * do_not_edit: true
 * source_ref: ${sourceRef}
 *
 * The Community Prompt routing decisions the \`approvePrompts\` callable routes
 * on (#1275), copied byte-for-byte from the one implementation in the app
 * package. Edit that source and re-run this script.
 */

import { normalizePool } from './poolVocab';

${blocks.join('\n\n')}\n`;

if (checkOnly) {
  let actual = '';
  try {
    actual = await readFile(outputPath, 'utf8');
  } catch {
    // A missing output is ordinary drift and is reported by the comparison.
  }
  if (actual !== expected) {
    process.stderr.write(`Generated routing mirror is stale: ${path.relative(repoRoot, outputPath)}\n`);
    process.exitCode = 1;
  } else {
    process.stdout.write(`Generated routing mirror is current: ${path.relative(repoRoot, outputPath)}\n`);
  }
} else {
  await writeFile(outputPath, expected, 'utf8');
  process.stdout.write(`Materialized ${path.relative(repoRoot, outputPath)} from ${sourceRef}\n`);
}
