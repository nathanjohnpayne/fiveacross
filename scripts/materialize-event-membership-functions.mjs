#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const sourcePath = path.join(repoRoot, 'src/data/eventMembership.ts');
const outputPath = path.join(repoRoot, 'functions/src/eventMembership.generated.ts');
const sourceRef = 'src/data/eventMembership.ts#event-membership-functions';
const checkOnly = process.argv.slice(2).includes('--check');

const unknownArgs = process.argv.slice(2).filter((arg) => arg !== '--check');
if (unknownArgs.length > 0) {
  throw new Error(`Unknown argument(s): ${unknownArgs.join(', ')}`);
}

const source = await readFile(sourcePath, 'utf8');
const blockPattern = /^\/\/ <event-membership-functions>\r?\n([\s\S]*?)^\/\/ <\/event-membership-functions>\r?$/gm;
const blocks = [...source.matchAll(blockPattern)].map((match) => match[1].replace(/\r\n/g, '\n').trimEnd());

if (blocks.length !== 3) {
  throw new Error(`Expected exactly 3 event-membership-functions blocks in ${sourceRef}; found ${blocks.length}.`);
}

const expected = `/**
 * @generated by scripts/materialize-event-membership-functions.mjs
 * do_not_edit: true
 * source_ref: ${sourceRef}
 *
 * Authorization-sensitive membership primitives are copied byte-for-byte from
 * the marked canonical source blocks. Edit that source and re-run this script.
 */

import type {
  MembershipBase,
  MembershipDoc,
  MembershipRole,
  MembershipStatus,
} from '../../src/domainTypes';

${blocks.join('\n\n')}\n`;

if (checkOnly) {
  let actual = '';
  try {
    actual = await readFile(outputPath, 'utf8');
  } catch {
    // A missing output is ordinary drift and is reported by the comparison.
  }
  if (actual !== expected) {
    process.stderr.write(`Generated membership mirror is stale: ${path.relative(repoRoot, outputPath)}\n`);
    process.exitCode = 1;
  } else {
    process.stdout.write(`Generated membership mirror is current: ${path.relative(repoRoot, outputPath)}\n`);
  }
} else {
  await writeFile(outputPath, expected, 'utf8');
  process.stdout.write(`Materialized ${path.relative(repoRoot, outputPath)} from ${sourceRef}\n`);
}
